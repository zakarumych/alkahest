use std::{env, ffi::OsString, fs::File, io::Read, path::PathBuf, process::ExitCode};

use alkahest_schema::{MAX_JSON_BYTES, Snapshot, Violation, check};

const HELP: &str = "Verify that formula versions preserve their declared schemas.

Usage: alkahest-schema check BASELINE CURRENT [--format text|json|github]
       alkahest-schema --help
       alkahest-schema --version

BASELINE and CURRENT are snapshots generated by alkahest_schema::Snapshot.
Exit codes: 0 = passed, 1 = version violations, 2 = invalid input or usage.
This command only reads snapshots; it never updates the baseline.
";

#[derive(Clone, Copy)]
enum Format {
    Text,
    Json,
    Github,
}

fn main() -> ExitCode {
    let args: Vec<OsString> = env::args_os().skip(1).collect();
    if args.len() == 1 && (args[0] == "--help" || args[0] == "-h") {
        print!("{HELP}");
        return ExitCode::SUCCESS;
    }
    if args.len() == 1 && (args[0] == "--version" || args[0] == "-V") {
        println!("alkahest-schema {}", env!("CARGO_PKG_VERSION"));
        return ExitCode::SUCCESS;
    }

    // Honor a valid output format even when another argument is malformed.
    let option_end = args
        .iter()
        .position(|arg| arg == "--")
        .unwrap_or(args.len());
    let format = args[..option_end]
        .windows(2)
        .filter(|pair| pair[0] == "--format")
        .filter_map(|pair| parse_format(&pair[1]).ok())
        .next_back()
        .unwrap_or(Format::Text);

    let result = parse_args(&args).and_then(|(baseline, current)| {
        let baseline = read_snapshot(&baseline)?;
        let current = read_snapshot(&current)?;
        check(&baseline, &current).map_err(|error| error.to_string())
    });
    match result {
        Ok(violations) => {
            let passed = violations.is_empty();
            match format {
                Format::Json => println!(
                    "{}",
                    serde_json::json!({
                        "status": if passed { "passed" } else { "failed" },
                        "violations": violations,
                        "errors": [],
                    })
                ),
                Format::Text => {
                    for violation in &violations {
                        eprintln!("{} {}: {}", violation.id, violation.path, violation.message);
                    }
                    println!("{}", summary(&violations));
                }
                Format::Github => {
                    for violation in &violations {
                        annotation(&format!(
                            "{} {}: {}",
                            violation.id, violation.path, violation.message
                        ));
                    }
                    println!("{}", summary(&violations));
                }
            }
            ExitCode::from(if passed { 0 } else { 1 })
        }
        Err(error) => {
            match format {
                Format::Json => println!(
                    "{}",
                    serde_json::json!({"status": "error", "violations": [], "errors": [error]})
                ),
                Format::Text => eprintln!("alkahest-schema: {error}"),
                Format::Github => annotation(&error),
            }
            ExitCode::from(2)
        }
    }
}

fn parse_format(value: &OsString) -> Result<Format, String> {
    match value.to_str() {
        Some("text") => Ok(Format::Text),
        Some("json") => Ok(Format::Json),
        Some("github") => Ok(Format::Github),
        _ => Err("--format must be text, json, or github".into()),
    }
}

fn parse_args(args: &[OsString]) -> Result<(PathBuf, PathBuf), String> {
    if args.first().is_none_or(|command| command != "check") {
        return Err(format!("expected the check command\n{HELP}"));
    }
    let mut paths = Vec::new();
    let mut format_seen = false;
    let mut positional_only = false;
    let mut args = args[1..].iter();
    while let Some(arg) = args.next() {
        if !positional_only && arg == "--" {
            positional_only = true;
        } else if !positional_only && arg == "--format" {
            if format_seen {
                return Err("--format may be specified only once".into());
            }
            format_seen = true;
            let value = args.next().ok_or("--format requires a value")?;
            parse_format(value)?;
        } else if !positional_only && arg.to_string_lossy().starts_with('-') {
            return Err(format!("unknown option: {}", arg.to_string_lossy()));
        } else {
            paths.push(PathBuf::from(arg));
        }
    }
    if paths.len() != 2 {
        return Err("check requires exactly two paths: BASELINE CURRENT".into());
    }
    Ok((paths.remove(0), paths.remove(0)))
}

fn read_snapshot(path: &PathBuf) -> Result<Snapshot, String> {
    let file =
        File::open(path).map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    let mut bytes = Vec::new();
    file.take(MAX_JSON_BYTES as u64 + 1)
        .read_to_end(&mut bytes)
        .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    if bytes.len() > MAX_JSON_BYTES {
        return Err(format!(
            "invalid snapshot {}: JSON exceeds {MAX_JSON_BYTES} bytes",
            path.display()
        ));
    }
    let text = String::from_utf8(bytes)
        .map_err(|error| format!("invalid snapshot {}: {error}", path.display()))?;
    Snapshot::from_json(&text)
        .map_err(|error| format!("invalid snapshot {}: {error}", path.display()))
}

fn summary(violations: &[Violation]) -> String {
    if violations.is_empty() {
        "schema check passed".into()
    } else {
        format!("schema check failed: {} violation(s)", violations.len())
    }
}

fn annotation(message: &str) {
    // Workflow-command data escapes differ from property escapes. The title is fixed.
    let escaped = message
        .replace('%', "%25")
        .replace('\r', "%0D")
        .replace('\n', "%0A");
    println!("::error title=Schema version check::{escaped}");
}
